"""Named fixture model slots for C++ maps, and the asset sheet for authors.

  python tools/campaign/model_ids.py [CURATION_NOTES]

Writes src/world/ModelIds.h (retro::model::<name> = fixture slot) from the
engine's built-in facility models and src/assets/library/catalog.json, and,
when given the curators' notes ("name | source | lore | size | placement |
facing" lines), docs/Design/descent-assets.md.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# Slots 0-62: the engine's own facility models (SoftwareRenderer m_facilityMeshes).
LEGACY = ['wall_panel_a', 'wall_panel_b', 'column', 'vent', 'ceiling_lamp', 'doorway_wide', 'generator', 'metal_shelf', 'wall_box',
          'door_wide_bottom', 'door_wide_top', 'computer', 'compressor', 'electrical_cabinet', 'tank_system', 'pallet', 'service_van',
          'wooden_crate', 'wooden_chair', 'wooden_table', 'extraction_fan', 'packing_crate', 'control_console', 'forklift', 'desk',
          'desk_corner', 'office_chair', 'crt_monitor', 'keyboard', 'pc_tower', 'cctv_tv', 'file_cabinet_wide', 'file_cabinet_tall',
          'desk_phone', 'mug', 'water_cooler', 'coffee_machine', 'bookcase', 'binder', 'converter', 'flue', 'stock_cage',
          'pendant_lamp', 'ibeam', 'pipe_riser', 'valve_wheel', 'turbine_casing', 'container_open', 'container_closed', 'drum',
          'vending_machine', 'bench', 'road_block', 'storage_tank', 'gas_cylinder', 'test_machine', 'metro_car', 'ticket_gate',
          'ticket_machine', 'trash_can', 'metro_map', 'platform_chair', 'metro_vending']

def main():
    cat = json.load(open(os.path.join(ROOT, 'src', 'assets', 'library', 'catalog.json')))
    rows = [(i, n, None) for i, n in enumerate(LEGACY)]
    for name, e in cat.items():
        rows.append((e['slot'], name, e))
    rows.sort()
    out = ['#pragma once', '// Fixture model slots by name, for C++ maps. Generated by',
           '// tools/campaign/model_ids.py from the engine facility models (0-62) and',
           '// src/assets/library/catalog.json. Sizes are the model\'s own metres',
           '// (width x depth x height); scale all three alike to keep proportions.',
           'namespace retro::model {']
    for slot, name, e in rows:
        ident = re.sub(r'\W', '_', name)
        size = ' // %.2f x %.2f x %.2f' % (e['width'], e['depth'], e['height']) if e else ''
        out.append('inline constexpr int %s=%d;%s' % (ident, slot, size))
    out.append('}')
    open(os.path.join(ROOT, 'src', 'world', 'ModelIds.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
    print('ModelIds.h: %d models' % len(rows))
    if len(sys.argv) > 1:
        notes = {}
        for line in open(sys.argv[1], encoding='utf-8'):
            parts = [p.strip() for p in line.split('|')]
            if len(parts) >= 5 and re.fullmatch(r'(med|lab|pwr|mine|cave|scrap)_\w+', parts[0]):
                notes[parts[0]] = parts
        doc = ['---', 'tags: [design, assets]', 'date: 2026-10-25', '---', '', '# Descent chapter models', '',
               'Imported from the purchased packs on 2026-10-25 and named for what they are in',
               'the facility. Use them as `model::name` (src/world/ModelIds.h). Sizes are the',
               "model's own metres; fixtures stretch the mesh to the width/depth/height you",
               'give, so scale all three alike. Facing notes are relative to the model;',
               'check in game, since packs differ.', '']
        groups = {'pwr': 'Power, water and maintenance', 'med': 'Medical', 'lab': 'Labs and research',
                  'mine': 'Mines', 'cave': 'Caverns', 'scrap': 'Scrap city'}
        for pre, title in groups.items():
            doc += ['## ' + title, '', '| Model | Slot | Size (m) | What it is | Placement | Facing |', '| --- | --- | --- | --- | --- | --- |']
            for slot, name, e in rows:
                if not name.startswith(pre + '_'): continue
                n = notes.get(name, [name, '', '', '', '', ''])
                lore = n[2] if len(n) > 2 else ''
                place = n[4] if len(n) > 4 else ''
                facing = n[5] if len(n) > 5 else ''
                doc.append('| %s | %d | %.2f x %.2f x %.2f | %s | %s | %s |' % (name, slot, e['width'], e['depth'], e['height'],
                           lore.replace('|', '/'), place.replace('|', '/'), facing.replace('|', '/')))
            doc.append('')
        open(os.path.join(ROOT, 'docs', 'Design', 'descent-assets.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(doc))
        print('descent-assets.md written')

if __name__ == '__main__':
    main()
