"""Write src/world/CampaignStateNames.inc: the state names the C++ maps use.

The campaign maps keep their states as hashes (stateId in ScriptDefinition.h),
so an exported .rmc could only name them "#1234567". The exporter looks each
hash up in this list (and in the list's names with the common suffixes and
trailing numbers the map builders append), and writes the readable name when
one hashes to the same id. A name that is missing just falls back to "#id",
which loads back to the identical state, so a stale list is never wrong, only
less readable. Rerun after adding states:  python tools/campaign/state_names.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(SRC, 'world', 'CampaignStateNames.inc')
LITERAL = re.compile(r'"([A-Za-z0-9_./-]{2,96})"')


def main():
    names = set()
    files = (glob.glob(os.path.join(SRC, 'world', '*.cpp')) + glob.glob(os.path.join(SRC, 'world', '*.h')) +
             glob.glob(os.path.join(SRC, 'game', '**', '*.cpp'), recursive=True))
    for path in files:
        if os.path.basename(path) == 'CampaignStateNames.inc':
            continue
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()
        for match in LITERAL.finditer(text):
            name = match.group(1)
            if re.search('[a-z]', name) and not name.endswith(('.png', '.obj', '.wav', '.txt', '.rmc', '.ppm', '.fbx')):
                names.add(name)
    lines = ['// Generated by tools/campaign/state_names.py; do not edit. See that script.']
    lines += ['"%s",' % name for name in sorted(names)]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('%d names -> %s' % (len(names), OUT))


if __name__ == '__main__':
    main()
