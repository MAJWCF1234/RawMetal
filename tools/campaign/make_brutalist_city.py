"""Writes custom maps/Brutalist City.rmc: a generated stress map for render distance underground.

A brutalist scrap city in the Dark Below, the work of something that was not human: 12 x 12 maps (288 m a
side), concrete slabs and towers up to 160 m, cantilevered blocks, sky bridges, scrap heaps, sodium and
resonance lamps; a gulf 96 m wide down the middle, crossed by one bridge 60 m up, where the player starts
looking east across it. No sky: every map has the same dark haze (the tone distance fades into) and asks to
be seen 600 m (MAP view). The east edge is open with nothing past it (the edge check's fade).

docs/Systems/render-distance.md "Underground megastructures".   python tools/campaign/make_brutalist_city.py
"""
import os
import random

N = 12                     # maps a side
GULF = range(4, 8)         # the columns of the gulf
BRIDGE_ROW = 6             # the bridge's row of maps
DECK = 60.0                # the bridge's walking height
CONCRETE = 5
HAZE = (0.10, 0.11, 0.135, 0.006)
VIEW = 600
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'custom maps', 'Brutalist City.rmc')


def g(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')


def main():
    rnd = random.Random(1987)
    lines = ['--- CUSTOM_CAMPAIGN_DATA_START ---', '# Generated by tools/campaign/make_brutalist_city.py: edit the script, not this file.']
    start = BRIDGE_ROW * N + (GULF.start - 1)
    lines.append('CAMPAIGN|BRUTALIST CITY|%d' % start)
    for row in range(N):
        for col in range(N):
            m = row * N + col
            ox, oy = col * 24, row * 24
            open_n, open_s, open_w = row > 0, row < N - 1, col > 0
            open_e = True                                   # the east edge of the city opens on nothing
            spawn = (20, 12, DECK) if m == start else (12, 12, 0)
            lines.append('MAP|%d|District %d-%d|%d|%d|%s|%s|%s|0|200|0.3|industrial_night|%d|%d|%d|%d|0|-1|0|11|0|-0.05|1|%s|%s|%s|%s||%d' % (
                m, row, col, ox, oy, g(spawn[0]), g(spawn[1]), g(spawn[2]), open_n, open_s, open_w, open_e,
                g(HAZE[0]), g(HAZE[1]), g(HAZE[2]), g(HAZE[3]), VIEW))
            lines.append('LAYER|%d|0|Undercity|0|0' % m)
            for r in range(24):
                lines.append('ROW|%d|0|%d|%s' % (m, r, '.' * 24))
            s = []
            gulf = col in GULF
            if not gulf:
                # Towers: two to four slabs, some carrying a wider block higher up (the cantilever).
                for _ in range(rnd.randint(2, 4)):
                    w, d = rnd.uniform(5, 11), rnd.uniform(5, 11)
                    x, y = rnd.uniform(0.5, 23.5 - w), rnd.uniform(0.5, 23.5 - d)
                    h = rnd.choice([rnd.uniform(25, 60), rnd.uniform(60, 110), rnd.uniform(110, 160)])
                    s.append((x, y, x + w, y + d, 0, h))
                    if rnd.random() < 0.5:
                        b = rnd.uniform(h * 0.4, h * 0.8)
                        ex = rnd.uniform(1, 4)
                        s.append((max(0, x - ex), max(0, y - ex), min(24, x + w + ex), min(24, y + d + ex), b, b + rnd.uniform(6, 14)))
                    # Lamps up the face: sodium, cold work light, or the red-violet of resonance.
                    for _ in range(rnd.randint(1, 3)):
                        z = rnd.uniform(4, h - 2)
                        k = rnd.choice([1900, 2100, 6500, 9000])
                        lines.append('LIGHT|%d|%s|%s|%s|0|0|1.6|22|%d' % (m, g(x + w / 2), g(y - 0.3), g(z), k))
                # Scrap at the foot: slabs fallen together.
                for _ in range(rnd.randint(1, 3)):
                    x, y = rnd.uniform(1, 20), rnd.uniform(1, 20)
                    s.append((x, y, x + rnd.uniform(1.5, 4), y + rnd.uniform(1.5, 4), 0, rnd.uniform(1, 5)))
            # Sky bridges between districts, crossing the map at a height.
            if not gulf and rnd.random() < 0.35:
                z = rnd.uniform(20, 120)
                if rnd.random() < 0.5:
                    s.append((0, 10.5, 24, 13.5, z, z + 2.5))
                else:
                    s.append((10.5, 0, 13.5, 24, z, z + 2.5))
            # The one bridge across the gulf, with parapets.
            if row == BRIDGE_ROW and GULF.start - 1 <= col <= GULF.stop:
                s.append((0, 10, 24, 14, DECK - 1.2, DECK))
                s.append((0, 9.8, 24, 10, DECK, DECK + 1.1))
                s.append((0, 14, 24, 14.2, DECK, DECK + 1.1))
                if col in GULF:
                    s.append((11, 11, 13, 13, 0, DECK - 1.2))       # a pier down into the dark
                    lines.append('LIGHT|%d|12|10.4|%s|0|0|1.2|14|2100' % (m, g(DECK + 2)))
            for x1, y1, x2, y2, b, t in s:
                lines.append('STRUCT|%d|%s|%s|%s|%s|%s|%s|0|%d' % (m, g(x1), g(y1), g(x2), g(y2), g(b), g(t), CONCRETE))
    lines.append('--- CUSTOM_CAMPAIGN_DATA_END ---')
    with open(OUT, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(OUT), len(lines), 'lines')


if __name__ == '__main__':
    main()
