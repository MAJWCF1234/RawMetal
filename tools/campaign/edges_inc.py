"""Generate only the Chapter 1 route-test edge contract; never rewrite maps."""
from pathlib import Path
import plan


def generate():
    rows = ["// Generated by tools/campaign/edges_inc.py from plan.CHUNKS; do not edit."]
    for chunk in plan.CHUNKS:
        if 34 <= chunk['idx'] <= 67:
            for edge in chunk['edges']:
                assert edge['side'] in 'NSEW' and edge['kind'] in ('seam', 'door')
                assert edge['a'] < edge['b']
                rows.append("{%d, '%s', %.6ff, %.6ff, %.6ff, %s}," % (
                    chunk['idx'], edge['side'], edge['a'], edge['b'], edge['z'],
                    'true' if edge['kind'] == 'door' else 'false'))
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    target = Path(plan.ROOT) / 'src/game/ChapterEdges.inc'
    target.write_text(generate(), encoding='utf-8', newline='\n')
    print(target)
